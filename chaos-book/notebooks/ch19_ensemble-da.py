@app.cell(hide_code=True)
def s6_md(mo):
    mo.md(
        r"""
    ## 6 · Deterministic or stochastic?

    Chapter 20 used the **perturbed-observation** EnKF: each member assimilates
    $y + \epsilon_i$ with $\epsilon_i \sim \mathcal{N}(0, \mathbf{R})$, because
    without that the analysis ensemble comes out too narrow. It is the original
    formulation and the easiest to write down.

    But those $\epsilon_i$ are *themselves* a finite sample, and they introduce a
    second sampling error on top of the one in $\mathbf{P}^f$. The **ETKF** avoids
    it by computing a single deterministic $k \times k$ transform whose analysis
    covariance is right by construction rather than in expectation:

    $$
    \mathbf{W}^a = \big[(k-1)\tilde{\mathbf{P}}^a\big]^{1/2},
    \qquad
    \tilde{\mathbf{P}}^a = \big[(k-1)\mathbf{I}
      + \mathbf{Y}^{f\top}\mathbf{R}^{-1}\mathbf{Y}^{f}\big]^{-1}.
    $$

    Each scheme below gets its own best radius *and* its own best inflation.
    """
    )
    return


@app.cell(hide_code=True)
def s6_kalman(mo):
    mo.md(
        r"""
    /// admonition | Verified: the ETKF is the Kalman filter for the covariance the ensemble has
        type: info

    For any ensemble size, the ETKF analysis mean and covariance equal the Kalman
    filter's computed with the ensemble's own sample covariance — to $10^{-12}$ and
    $10^{-11}$ respectively. `chaoslib` asserts this at $k = 4, 7, 12, 40$ on a
    6-variable system, **including $k < n$**, where the sample covariance is singular
    and the ordinary Kalman form would need a pseudo-inverse. The ETKF never inverts
    anything of size $n$: it works inside the ensemble's own $(k-1)$-dimensional
    subspace, which is simultaneously the reason it is cheap and the reason it needs
    localisation.

    The implementation uses the **symmetric** square root. A Cholesky factor also
    satisfies $\mathbf{W}\mathbf{W}^{\top} = (k-1)\tilde{\mathbf{P}}^a$, but it
    shifts the analysis mean while still producing the correct analysis covariance —
    a bug that a covariance check cannot see.
    ///
    """
    )
    return


