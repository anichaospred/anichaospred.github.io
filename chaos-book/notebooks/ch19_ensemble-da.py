@app.cell
def helpers(DT, FORCING, N_SITES, integrate, np, systems):
    # A spun-up Lorenz 96 attractor, live: one integration, fast even in
    # Pyodide, and the reader should be able to see where the ensemble
    # covariance in section 1 comes from.
    _start = systems.lorenz96_uniform_state(FORCING, N_SITES) + np.r_[
        0.01, np.zeros(N_SITES - 1)
    ]
    attractor = integrate.rk4(
        systems.lorenz96, _start, integrate.trajectory_grid(100.0, DT),
        forcing=FORCING,
    )[4000:]
    climatology = np.cov(attractor[::5].T)

    def advance(states, steps, dt=DT):
        grid = np.linspace(0.0, steps * dt, steps + 1)
        return integrate.rk4(
            systems.lorenz96, states, grid, forcing=FORCING
        )[-1]

    def ring_separation(n_state):
        index = np.arange(n_state)
        gap = np.abs(index[:, None] - index[None, :])
        return np.minimum(gap, n_state - gap)

    return advance, attractor, climatology, ring_separation


