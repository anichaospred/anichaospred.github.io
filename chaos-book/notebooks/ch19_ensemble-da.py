    _cure = dict(zip(CURE_LABELS, np.asarray(CURE_ERROR)))
    _cbeta = dict(zip(CURE_LABELS, CURE_BETA))
    _best = [float(_betas[int(np.nanargmin(_err[:, j]))]) for j in range(len(_members))]
    _letkf5 = float(np.asarray(MAP_ERROR).reshape(len(MAP_MEMBERS), -1)[0].min())
    _gain = 100 * (1 - _cure["BOTH"] / _cure["LOC"])
