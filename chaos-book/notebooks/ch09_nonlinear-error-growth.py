@app.cell
def helpers(
    L63_AMPLITUDES,
    L63_EARLY_RATE,
    L63_ERRORS,
    L63_LAMBDA1,
    L63_RATE_INTERCEPT,
    L63_RATE_SLOPE,
    L63_SAT_MEAN,
    L63_SAT_RMS,
    L63_TIMES,
    L96_AMPLITUDES,
    L96_EARLY_RATE,
    L96_ERRORS,
    L96_LAMBDA1,
    L96_RATE_INTERCEPT,
    L96_RATE_SLOPE,
    L96_SAT_MEAN,
    L96_SAT_RMS,
    L96_TIMES,
    np,
):
    def bundle(key):
        """Everything about one system, keyed by name."""
        if key == "L63":
            times, errors, amps = L63_TIMES, L63_ERRORS, L63_AMPLITUDES
            sat_mean, sat_rms, lam1 = L63_SAT_MEAN, L63_SAT_RMS, L63_LAMBDA1
            slope, intercept, early = (
                L63_RATE_SLOPE, L63_RATE_INTERCEPT, L63_EARLY_RATE
            )
            label, unit = "Lorenz 63", "MTU"
        else:
            times, errors, amps = L96_TIMES, L96_ERRORS, L96_AMPLITUDES
            sat_mean, sat_rms, lam1 = L96_SAT_MEAN, L96_SAT_RMS, L96_LAMBDA1
            slope, intercept, early = (
                L96_RATE_SLOPE, L96_RATE_INTERCEPT, L96_EARLY_RATE
            )
            label, unit = "Lorenz 96", "time units"
        t = np.asarray(times, dtype=float)
        e = np.asarray(errors, dtype=float).reshape(len(amps), t.size)
        return dict(
            t=t, e=e, amps=np.asarray(amps, dtype=float),
            sat_mean=sat_mean, sat_rms=sat_rms, lambda1=lam1,
            slope=slope, intercept=intercept, early=early,
            label=label, unit=unit,
        )

    def crossing(t, curve, level):
        """First time a curve reaches `level`, linearly interpolated."""
        hit = np.nonzero(curve >= level)[0]
        if hit.size == 0:
            return float("nan")
        i = int(hit[0])
        if i == 0:
            return float(t[0])
        return float(np.interp(level, [curve[i - 1], curve[i]], [t[i - 1], t[i]]))

    return bundle, crossing


