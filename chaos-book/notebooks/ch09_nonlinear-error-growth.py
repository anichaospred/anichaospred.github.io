    from scipy.optimize import curve_fit

    _b = bundle(str(system_choice.value))
    _t, _measured = _b["t"], _b["e"][0]
    _sat = _b["sat_mean"]
    _true_e0 = float(_b["amps"][0])
    _space = str(fit_space.value)

    def _fit(space):
        if space == "linear":
            e0, rate, _ = errorgrowth.fit_logistic_error_growth(
                _t, _measured, saturation=_sat
            )
            return e0, rate

        def model(tt, log_e0, rate):
            return np.log(
                errorgrowth.logistic_error_growth(tt, np.exp(log_e0), rate, _sat)
            )

        popt, _ = curve_fit(
            model, _t, np.log(_measured),
            p0=(np.log(_measured[0]), 1.0), maxfev=40000,
        )
        return float(np.exp(popt[0])), float(popt[1])

