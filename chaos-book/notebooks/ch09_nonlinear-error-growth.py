@app.cell(hide_code=True)
def s4_figure(
    C_MEAN,
    C_PERT,
    C_SAT,
    C_TRUTH,
    DAYS_PER_TU,
    bundle,
    finish_mpl,
    mo,
    mpl_panels,
    np,
    system_choice,
):
    _b = bundle(str(system_choice.value))
    _curve = _b["e"][0]
    _rate = np.gradient(np.log(_curve), _b["t"])
    _fraction = _curve / _b["sat_mean"]

    _fig, _ax = mpl_panels(
        2,
        titles=("Local doubling time vs error size",
                "What the logistic model implies"),
        height=3.5,
    )
    _w = (_fraction > 1e-3) & (_fraction < 0.9) & (_rate > 0.02)
    _ax[0].semilogx(_fraction[_w], np.log(2.0) / _rate[_w], linewidth=1.0,
                    alpha=0.45, color=C_TRUTH)
    # Smooth it: the local rate of a noisy curve is noisier still.
    _order = np.argsort(_fraction[_w])
    _xs, _ys = _fraction[_w][_order], (np.log(2.0) / _rate[_w])[_order]
    _bins = np.logspace(-3, np.log10(0.9), 22)
    _mid, _med = [], []
    for _lo, _hi in zip(_bins[:-1], _bins[1:]):
        _m = (_xs >= _lo) & (_xs < _hi)
        if _m.sum() > 2:
            _mid.append(np.sqrt(_lo * _hi))
            _med.append(float(np.median(_ys[_m])))
    _ax[0].semilogx(_mid, _med, marker="o", markersize=4.5, color=C_PERT,
                    linewidth=1.8, label="binned median")
    _ax[0].axhline(np.log(2.0) / _b["lambda1"], color=C_SAT, linewidth=1.3,
                   linestyle="--",
                   label=f"$\\ln2/\\lambda_1$ = {np.log(2.0)/_b['lambda1']:.3f}")
    _ax[0].set_xlabel("$E/E_\\infty$")
    _ax[0].set_ylabel(f"local doubling time ({_b['unit']})")
    _ax[0].set_ylim(0, min(6.0, 4.0 * np.log(2.0) / _b["lambda1"]))
    _ax[0].legend(loc="upper left", fontsize=6.5, framealpha=0.9)

    _f = np.linspace(0.001, 0.95, 200)
    _ax[1].plot(_f, np.log(2.0) / (_b["intercept"] * (1.0 - _f)),
                color=C_TRUTH, linewidth=1.8, label="logistic")
    _ax[1].plot(_f, np.log(2.0) / np.maximum(
        _b["intercept"] + _b["slope"] * _f, 1e-6),
        color=C_PERT, linewidth=1.5, linestyle="--", label="fitted line")
    _ax[1].axhline(np.log(2.0) / _b["lambda1"], color=C_SAT, linewidth=1.2,
                   linestyle=":")
    _ax[1].set_xlabel("$E/E_\\infty$")
    _ax[1].set_ylabel(f"doubling time ({_b['unit']})")
    _ax[1].set_ylim(0, 6.0 * np.log(2.0) / _b["lambda1"])
    _ax[1].legend(loc="upper left", fontsize=6.5, framealpha=0.9)
    finish_mpl(_fig, suptitle=_b["label"])

    _at = {}
    for _target in (0.001, 0.01, 0.1, 0.3, 0.5, 0.7):
        _i = int(np.argmin(np.abs(_fraction - _target)))
        _at[_target] = (
            np.log(2.0) / _rate[_i] if _rate[_i] > 0.02 else float("inf")
        )
    _rows = "\n".join(
        f"| {k:g} | {v:.3f} | {v * DAYS_PER_TU:.2f} |" for k, v in _at.items()
    )
    _base = np.log(2.0) / _b["lambda1"]

    mo.vstack([
        mo.md(
            r"""---
    ## 4 · So what is "the" doubling time?

    Section 3 established that $d\ln E/dt$ falls as $E$ grows. The doubling
    time is $\ln 2$ divided by that, so it is not a property of the system —
    it is a property of the system *and the error amplitude you measured it at*.
    """
        ),
        _fig,
        mo.md(
            f"""
| $E/E_\\infty$ | local doubling time ({_b['unit']}) | days at 5 days/unit |
|---|---|---|
{_rows}

At infinitesimal amplitude the doubling time is
$\\ln2/\\lambda_1 = {_base:.3f}$ {_b['unit']}. By a tenth of saturation it is
{_at[0.1]:.3f}, by half {_at[0.5]:.3f}, and as $E \\to E_\\infty$ it diverges.
The number quadruples across the range where a forecast is actually useful.

**The operational consequence runs in a direction worth being careful about.**
An error-doubling time measured from real forecasts is measured from errors that
are *already large* — an operational analysis error is a substantial fraction of
saturation, not $10^{{-8}}$ of it. So the doubling time inferred that way is
longer than $\\ln2/\\lambda_1$, and using it to extrapolate *backwards* to
small errors **underestimates** how fast small errors grow. Conversely, using
$\\lambda_1$ to extrapolate *forwards* to large errors overestimates growth
there, and so underestimates the useful horizon.

Both mistakes are available, they point in opposite directions, and neither is
detectable from a single number. This is why chapter 13 — on what operational
forecast errors actually do — cannot simply quote a $\\lambda$, and why the
honest summary of a forecast's decay is the whole curve rather than one rate.
"""
        ),
    ])
    return


