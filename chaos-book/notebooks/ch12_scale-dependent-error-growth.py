@app.cell(hide_code=True)
def title(mo):
    mo.md(
        r"""
    # Chapter 12 · Scale-Dependent Error Growth and the Intrinsic Limit

    **Part IV — Many scales, many degrees of freedom.**

    **The forecasting question.** Every predictability estimate in this book so
    far has had the same shape. An error of size $\delta_0$ grows at rate
    $\lambda_1$, so a useful forecast lasts
    $\lambda_1^{-1}\ln(\delta_{\rm sat}/\delta_0)$ — and as $\delta_0 \to 0$
    that grows without bound. Chapter 8 put a price on it: $\ln 10/\lambda_1$ =
    3.8 days per decimal digit of initial precision, and the next digit buys 3.8
    days again. Slow, expensive, but *unlimited*.

    So: is there any reason a forecast could not be extended indefinitely by
    observing well enough?

    Lorenz (1969) said yes, and the argument is more troubling than the
    butterfly effect. Suppose the system has a **spectrum** of scales, and small
    scales grow faster than large ones — as they do in any turbulent flow.
    Then error at the smallest scale saturates almost at once, contaminates the
    next scale up, and so on. The total time to climb the ladder is a *sum*, and
    if the terms shrink fast enough that sum **converges**. Error introduced at
    an arbitrarily small scale then reaches the largest scale in a finite time,
    and improving the resolution of an observing system stops buying anything.

    Whether that happens turns on a single exponent, and this chapter measures
    where the boundary is.

    ---

    ## The model

    Discretise into octave bands. Band $n$ has scale $L\,2^{-n}$ and growth rate

    $$\lambda_n = \lambda_0\,2^{\alpha n},$$

    so $\alpha$ is how much faster small scales grow than large. Kolmogorov
    scaling gives an eddy turnover time $\tau \sim \varepsilon^{-1/3}\ell^{2/3}$
    and hence $\alpha = 2/3$. **Lorenz 63 and Lorenz 96 have $\alpha = 0$** —
    one growth rate, the same at every scale — which is exactly why nothing in
    Part III could have raised this question.

    Each band's error is measured against its own saturation level, so
    $e_n \in [0,1]$, and grows logistically while being forced by the band one
    octave smaller:

    $$\frac{de_n}{dt} = \lambda_n\bigl(e_n + \kappa e_{n+1}\bigr)\bigl(1 - e_n\bigr).$$

    With one band the second term is absent and this is exactly chapter 9's
    logistic model — a reduction `chaoslib` checks to $10^{-8}$.

    ---

    ## What "better observations" means here

    This is the step that makes the argument work, and it is easy to slide past.

    An observing system has a **resolution**. About scales finer than it we know
    nothing at all, so the error there starts at *saturation*. Improving the
    system therefore means **adding a band** — seeing one octave further down —
    and not reducing an amplitude. Those two kinds of improvement behave
    completely differently, and Sections 2 and 3 measure both.

    | Section | The question |
    |---|---|
    | 1 | What does the cascade look like? |
    | 2 | Does resolving finer scales keep buying lead time? |
    | 3 | Does a smaller initial error? Where does it have to be? |
    | 4 | Does a real dynamical system do this? |
    """
    )
    return


