@app.cell(hide_code=True)
def s4_figure(
    C_CONTEXT,
    C_MEAN,
    C_OBS,
    C_PERT,
    C_SAT,
    C_SPREAD,
    C_TRUTH,
    DAYS_PER_TU,
    LAMBDA1_L96,
    TWO_SCALE_AMPLITUDES,
    TWO_SCALE_FAST_FASTERR,
    TWO_SCALE_FAST_SLOWERR,
    TWO_SCALE_LAMBDA1,
    TWO_SCALE_SAT_FAST,
    TWO_SCALE_SAT_SLOW,
    TWO_SCALE_SEP,
    TWO_SCALE_SEP_TIMES,
    TWO_SCALE_SLOW_FASTERR,
    TWO_SCALE_SLOW_SLOWERR,
    TWO_SCALE_TIMES,
    finish_mpl,
    mo,
    mpl_panels,
    np,
    seed_choice,
):
    _t = np.asarray(TWO_SCALE_TIMES, dtype=float)
    _n = _t.size
    _amps = np.asarray(TWO_SCALE_AMPLITUDES, dtype=float)
    _curves = {
        "FAST": (np.asarray(TWO_SCALE_FAST_SLOWERR).reshape(_amps.size, _n),
                 np.asarray(TWO_SCALE_FAST_FASTERR).reshape(_amps.size, _n)),
        "SLOW": (np.asarray(TWO_SCALE_SLOW_SLOWERR).reshape(_amps.size, _n),
                 np.asarray(TWO_SCALE_SLOW_FASTERR).reshape(_amps.size, _n)),
    }
    _where = str(seed_choice.value)
    _slow_err, _fast_err = _curves[_where]

    def _time_to(curve, level):
        _hit = np.nonzero(curve >= level)[0]
        if _hit.size == 0 or _hit[0] == 0:
            return np.nan
        _i = _hit[0]
        return float(np.interp(level, [curve[_i - 1], curve[_i]],
                               [_t[_i - 1], _t[_i]]))

    _fig, _ax = mpl_panels(
        3,
        titles=("Error in the slow variables", "Error in the fast variables",
                "Growth rate of the slow error"),
        height=3.6,
    )
    _cols = (C_TRUTH, C_MEAN, C_SPREAD, C_PERT, C_OBS)
    for _i, (_amp, _colour) in enumerate(zip(_amps, _cols)):
        _ax[0].semilogy(_t, np.maximum(_slow_err[_i], 1e-12), linewidth=1.4,
                        color=_colour, label=f"{_amp:.0e}")
        _ax[1].semilogy(_t, np.maximum(_fast_err[_i], 1e-12), linewidth=1.4,
                        color=_colour)
    _ax[0].axhline(TWO_SCALE_SAT_SLOW, color=C_SAT, linewidth=1.2,
                   linestyle="--", label="saturation")
    _ax[0].set_xlabel("time (time units)")
    _ax[0].set_ylabel("RMS slow error")
    _ax[0].set_ylim(1e-11, 30)
    _ax[0].legend(loc="lower right", fontsize=6.0, framealpha=0.9, ncol=2)

    _ax[1].axhline(TWO_SCALE_SAT_FAST, color=C_SAT, linewidth=1.2,
                   linestyle="--")
    _ax[1].set_xlabel("time (time units)")
    _ax[1].set_ylabel("RMS fast error")
    _ax[1].set_ylim(1e-11, 30)

    # The slow error's growth rate, fitted in its exponential phase.
    _rates = []
    for _i in range(_amps.size):
        _e = _slow_err[_i]
        _w = (_e > 1e-3 * TWO_SCALE_SAT_SLOW) & (_e < 0.2 * TWO_SCALE_SAT_SLOW)
        _rates.append(
            float(np.polyfit(_t[_w], np.log(_e[_w]), 1)[0]) if _w.sum() > 4
            else np.nan
        )
    _rates = np.array(_rates)
    _ax[2].plot(-np.log10(_amps), _rates, marker="o", markersize=5,
                color=C_TRUTH, linewidth=1.6, label="fitted growth rate")
    _ax[2].axhline(LAMBDA1_L96, color=C_MEAN, linewidth=1.2, linestyle=":",
                   label=f"single-scale L96: {LAMBDA1_L96}")
    _ax[2].axhline(TWO_SCALE_LAMBDA1, color=C_SAT, linewidth=1.2,
                   linestyle="--", label=f"coupled $\\lambda_1$ = {TWO_SCALE_LAMBDA1:.1f}")
    _ax[2].set_yscale("log")
    _ax[2].set_xlabel("digits of initial accuracy")
    _ax[2].set_ylabel("growth rate (per time unit)")
    _ax[2].legend(loc="center right", fontsize=6.0, framealpha=0.9)
    finish_mpl(_fig, suptitle=f"Two-scale Lorenz 96, error seeded in the "
                              f"{_where.lower()} variables, 32-member mean")

    _t10 = np.array([_time_to(_slow_err[_i], 0.1 * TWO_SCALE_SAT_SLOW)
                     for _i in range(_amps.size)])
    _slope = float(np.polyfit(-np.log10(_amps), _t10, 1)[0])
    _other = "SLOW" if _where == "FAST" else "FAST"
    _other_t10 = np.array([
        _time_to(_curves[_other][0][_i], 0.1 * TWO_SCALE_SAT_SLOW)
        for _i in range(_amps.size)
    ])
    _other_slope = float(np.polyfit(-np.log10(_amps), _other_t10, 1)[0])

    _rows = "\n".join(
        f"| {a:.0e} | {_time_to(_fast_err[i], 0.5*TWO_SCALE_SAT_FAST):.3f} | "
        f"{_t10[i]:.3f} | {_rates[i]:.3f} |"
        for i, a in enumerate(_amps)
    )

    mo.vstack([
        mo.md(
            r"""---
    ## 4 · Does a real dynamical system do this?

    The cascade model of Sections 1–3 is a *model of error*, not of a flow: its
    bands are postulated, and so are their growth rates. So here is a genuine
    dynamical system with two scales — 8 slow variables coupled to 256 fast ones
    that move ten times faster and carry a tenth the amplitude:

    $$\frac{dX_k}{dt} = X_{k-1}(X_{k+1} - X_{k-2}) - X_k + F
      - \frac{hc}{b}\sum_{j\in k} Y_j, \qquad
      \frac{dY_j}{dt} = cb\,Y_{j+1}(Y_{j-1} - Y_{j+2}) - cY_j
      + \frac{hc}{b}X_{k(j)}.$$

    Set the coupling $h$ to zero and the slow equations become Lorenz 96
    exactly. Leave it on and the two subsystems exchange energy, conserving
    $\tfrac12(\sum X^2 + \sum Y^2)$ — both checked in `chaoslib`'s tests.

    Perturb *only* the fast variables and see whether the slow ones notice."""
        ),
        mo.hstack([seed_choice], justify="start"),
        _fig,
        mo.md(
            f"""
| initial error | fast error to half sat. | slow error to 10% sat. | slow growth rate |
|---|---|---|---|
{_rows}

**The mechanism is there, cleanly.** The middle panel shows the fast error
saturating first — within {_time_to(_fast_err[0], 0.5*TWO_SCALE_SAT_FAST):.2f}
time units from the largest seed — after which the slow error grows at
**{np.nanmean(_rates[1:]):.2f} per time unit** whatever amplitude the
perturbation started at. The third panel makes that the point: the fitted growth
rate is flat across eight decades of initial accuracy. Once the small scales are
wrong, the large scales lose predictability at a rate the *large-scale* dynamics
set, and the size of the original small-scale error has stopped mattering.

**But the finite limit is absent.** Reducing the initial error buys
{_slope:.4f} time units per decade when it is seeded in the
{_where.lower()} variables, against {_other_slope:.4f} in the
{_other.lower()} ones — a difference of
{100 * abs(_slope - _other_slope) / max(_slope, _other_slope):.0f}%. It makes
essentially no difference where the error is put, and neither case shows any
sign of converging. **Two scales are not a cascade.** The bounded horizon of
Section 2 needed a *spectrum*, and this model has two rungs of one.

That is worth stating plainly, because two-scale Lorenz 96 is the standard
testbed for assimilation with unresolved scales and it would be easy to read
this figure as a demonstration of Lorenz's limit. It is a demonstration of the
mechanism only.
"""
        ),
        mo.callout(
            mo.md(
                f"""### And a warning about $\\lambda_1$

The leading Lyapunov exponent of this coupled system, measured by twin
trajectories, is **{TWO_SCALE_LAMBDA1:.1f} per time unit** — the dashed line in
the third panel, an order of magnitude above everything else on it. It is set by
the *fast* subsystem, because that is where the fastest-growing direction lives.

Taken at face value as "the" error-doubling time it gives
{np.log(2)/TWO_SCALE_LAMBDA1:.4f} time units, or
**{np.log(2)/TWO_SCALE_LAMBDA1*DAYS_PER_TU:.2f} days** at five days per unit,
which would put weather predictability at a few hours. The slow variables — the
ones a forecast is actually about — double every
{np.log(2)/np.nanmean(_rates[1:]):.3f} time units,
**{np.log(2)/np.nanmean(_rates[1:])*DAYS_PER_TU:.2f} days**. So $\\lambda_1$
overstates large-scale error growth by a factor of
**{TWO_SCALE_LAMBDA1/np.nanmean(_rates[1:]):.1f}**.

Chapter 7 introduced $\\lambda_1$ as *the* growth rate and chapter 11 measured
it for a forty-variable system. This is the correction: in a system with
well-separated scales, $\\lambda_1$ answers "how fast does the fastest thing
grow", and the predictability of the large scales is a different question with a
different answer. Reporting the first as though it were the second is a real and
easy mistake."""
            ),
            kind="warn",
        ),
    ])
    return


