def s3_note(
    CORR_ONESTEP_TRACK, TRACK_DELTA0, TRACK_EMULATOR_HALF, TRACK_TRUTH_HALF,
    N_STABLE, mo,
):
    mo.md(
        rf"""
    **The truth keeps that error usable for {TRACK_TRUTH_HALF} time units. The emulator
    loses skill in {TRACK_EMULATOR_HALF}** — a factor of
    {TRACK_TRUTH_HALF / TRACK_EMULATOR_HALF:.1f} shorter from the same starting error.

    The reason is in the right-hand panel, and it is not subtle once stated: an
    initial-condition error is injected **once** and then amplified. Model error is
    injected **at every step** and then amplified. The emulator is not solving the same
    problem as a perfect model with a bad initial condition, so chapter 3's law — which
    assumes a single perturbation growing freely — is the wrong law for it. It gives an
    upper bound, and a generous one.

    This is chapter 21's subject arriving in a new form, and it is the honest answer to
    "the one-step error is tiny, so why is the forecast short". It also explains why
    one-step error is a *usable but weak* guide: across the {int(N_STABLE)} stable
    configurations, the correlation between log one-step error and tracking time is
    ${CORR_ONESTEP_TRACK}$ — the right sign and far from decisive.
    """
    )
    return


