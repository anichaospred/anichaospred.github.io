@app.cell(hide_code=True)
def s5_md(mo):
    mo.md(
        r"""
    ## 5 · The timestep, and why filtering was worth a computer

    There is a second reason the fast mode is a problem, and it is arithmetic rather
    than physics. An explicit scheme is stable only while information moves less than
    about a grid cell per step — the Courant–Friedrichs–Lewy condition, published in
    1928, six years after Richardson's book. The relevant speed is the **fastest signal
    in the system**, and in the primitive equations that is the external gravity wave at
    $c = \sqrt{gH} \approx 280$ m/s, not the wind at 30.

    So a model that carries the gravity wave pays for it in timesteps, and the wave
    carries no forecast information whatever. That is the argument for **filtering**:
    write down equations from which the fast mode has been removed analytically. The
    barotropic vorticity equation,

    $$
    \partial_t \zeta + J(\psi, \zeta) = 0, \qquad \zeta = \nabla^2 \psi,
    $$

    is the simplest such model — it has no gravity waves *by construction*, because it
    has no divergence and no free surface. It is what Charney, Fjørtoft and von Neumann
    integrated on ENIAC in 1950 *[citation needed]*, and it is why that forecast was
    possible on a machine of that size.
    """
    )
    return


