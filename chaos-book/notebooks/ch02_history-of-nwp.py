@app.cell(hide_code=True)
def s1_md(mo):
    mo.md(
        r"""
    ## 1 · What Richardson actually did

    Richardson took the primitive equations — the same equations an operational model
    solves today — discretised central Europe on a grid of a few hundred kilometres,
    took an observed state from 20 May 1910, and stepped forward six hours with a pencil.
    The work took him something like six weeks *[citation needed]*.

    He knew perfectly well it was too slow to be useful, and he did the arithmetic on
    that too: **64,000 human computers**, each handling one grid column, working in a
    great hall with signals passed between them, would be needed to keep pace with the
    weather *[citation needed]*. It is the most famous image in the subject, and it was
    a serious estimate, not a joke.

    What he got was a six-hour surface-pressure change of 145 hPa. To see how small an
    error that needs, hold the question the right way round: **not "how could he be so
    wrong" but "how little would it take".** The rest of this chapter answers that
    quantitatively, and the answer is a spurious wind of a couple of metres per second
    — well inside the observational uncertainty of 1910, and for that matter inside the
    uncertainty of a modern analysis in a data-sparse region.
    """
    )
    return


