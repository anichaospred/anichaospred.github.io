@app.cell(hide_code=True)
def s2_md(INERTIAL_PERIOD_HOURS, ROSSBY_RADIUS, WAVE_SPEED, mo):
    mo.md(
        rf"""
    ## 2 · Two modes, one system

    Linearise the shallow-water equations about a state of rest with depth $H$ and the
    normal modes are exact:

    $$
    \omega^2 = f^2 + gH k^2 .
    $$

    Two features of that expression carry the whole chapter. There is a **floor**: no
    inertia-gravity wave is slower than $f$, a period of
    {INERTIAL_PERIOD_HOURS:.1f} hours at mid-latitudes. And $\omega$ **rises without
    bound** with $k$, so refining the grid makes the system stiffer rather than better
    behaved.

    With $H = 8000$ m — the external mode, the one Richardson's equations carried — the
    gravity-wave speed is $c = \sqrt{{gH}} = {WAVE_SPEED:.0f}$ m/s and the Rossby radius
    is $c/f = {ROSSBY_RADIUS/1000:.0f}$ km. That last number matters: it is *comparable
    to a synoptic weather system*, so the balanced and unbalanced parts of an analysis
    are not separated by scale and cannot be told apart by looking at a map.

    Against that there is a **balanced** state which carries no fast mode at all:
    $u = 0$ with $f v = g\,\partial_x h$. In this system that is not an approximation.
    """
    )
    return


