@app.cell(hide_code=True)
def s1_note(
    CLOSING_RESIDUAL,
    FITTED_RATES,
    GENERATOR_EIGS,
    LAM,
    LEAK_RESIDUAL,
    MU,
    ROLLOUT_ERROR,
    SLOW_TOTAL,
    SOLUTION_ERROR,
    TRUNCATED_RESIDUAL,
    mo,
    np,
):
    def _sci(value, digits=1):
        _mantissa, _exponent = f"{value:.{digits}e}".split("e")
        return rf"{_mantissa}\times 10^{{{int(_exponent)}}}"

    _eigs = np.asarray(GENERATOR_EIGS)
    _fitted = np.asarray(FITTED_RATES)
    mo.md(
        rf"""
    **Three checks, before anything is claimed from it.**

    * **The closed-form solution.** The system integrates exactly, and the analytic
      solution agrees with RK4 to ${_sci(SOLUTION_ERROR)}$ over
      {SLOW_TOTAL:.0f} time units — so the integrator and the operator can be checked
      against each other's failures rather than sharing them.
    * **The spectrum.** $\mathbf{{A}}$'s eigenvalues are
      ${_eigs[0]:.3f}$, ${_eigs[1]:.3f}$, ${_eigs[2]:.3f}$ against an exact
      $\lambda = {LAM:.2f}$, $2\mu = {2 * MU:.2f}$, $\mu = {MU:.2f}$. Note that there
      are **three**, where the Jacobian of a two-dimensional system has two. The extra
      one is $2\mu$, and it is not an artefact: products of Koopman eigenfunctions are
      Koopman eigenfunctions, and their eigenvalues *add*. The operator's spectrum is
      richer than the flow's, always.
    * **Fitted from data alone.** Handed nothing but a trajectory and the three
      observables, least squares returns the same rates —
      ${_fitted[0]:.4f}$, ${_fitted[1]:.4f}$, ${_fitted[2]:.4f}$ — with a closure
      residual of ${_sci(CLOSING_RESIDUAL)}$. **The linear model then reproduces the
      entire nonlinear trajectory** over {SLOW_TOTAL:.0f} time units to
      ${_sci(ROLLOUT_ERROR)}$, by repeated multiplication by a $3\times3$ matrix.

    ---

    ### The result that spoils the obvious plan

    The obvious plan is: use more observables. The right-hand panel above says it does
    not work that way.

    Drop $x_1^2$ and the residual is ${_sci(TRUNCATED_RESIDUAL)}$ — eleven orders of
    magnitude worse, from a dictionary one observable smaller. That much is expected.
    But now **add** an observable to the dictionary that closes. Admitting $x_1x_2$ —
    a perfectly reasonable, low-order, physically natural term — takes the residual from
    ${_sci(np.asarray([CLOSING_RESIDUAL])[0])}$ to ${_sci(7.5e-06)}$: a **larger
    dictionary, containing the closing one, that no longer closes.**

    The reason is exact and checkable:

    $$
    \frac{{d}}{{dt}}\left(x_1x_2\right)
      = (\mu + \lambda)\,x_1x_2 - \lambda\,x_1^3 ,
    $$

    verified against the trajectory to ${_sci(LEAK_RESIDUAL)}$ (finite-difference
    error). Admitting $x_1x_2$ opens a leak into $x_1^3$, which the dictionary cannot
    absorb. Admit $x_1^3$ as well and it closes again.

    **Closure is a property of the span, not of the size.** It is not a resolution that
    can be increased until the answer converges — it is an algebraic condition that a
    dictionary either satisfies or does not, and a bigger dictionary is not a safer one.
    The monomial hierarchy — the right-hand group of bars, each labelled with its size —
    shows the generic case: each order leaks into the next, so the residual falls
    steadily and **never** reaches the three-observable dictionary's machine precision. Fifteen carefully chosen terms lose
    to three correct ones by seven orders of magnitude.

    Now take that to an attractor, where nobody knows the right observables.
    """
    )
    return


