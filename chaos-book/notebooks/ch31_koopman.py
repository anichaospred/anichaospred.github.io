@app.cell(hide_code=True)
def s1_md(mo):
    mo.md(
        r"""
    ## 1 · A system where the linearisation is exact and finite

    There is a class of nonlinear systems for which the infinite-dimensional space is
    not needed: a **finite** set of observables closes under $\mathcal{K}$. The standard
    example is the slow-manifold normal form,

    $$
    \dot x_1 = \mu x_1, \qquad \dot x_2 = \lambda\left(x_2 - x_1^2\right),
    \qquad \lambda \ll \mu < 0,
    $$

    a fast variable slaved to a slow one — the structure behind every quasi-equilibrium
    closure in atmospheric modelling. Trajectories collapse onto the parabola
    $x_2 = x_1^2$ on the fast timescale and then slide down it on the slow one.

    It is nonlinear, and yet on the three observables $g = (x_1,\, x_2,\, x_1^2)$ the
    chain rule gives

    $$
    \dot g = \mathbf{A}g, \qquad
    \mathbf{A} = \begin{pmatrix}
      \mu & 0 & 0 \\ 0 & \lambda & -\lambda \\ 0 & 0 & 2\mu
    \end{pmatrix}.
    $$

    The third row is the whole trick: $\frac{d}{dt}x_1^2 = 2x_1\dot x_1 = 2\mu x_1^2$, so
    the *square* of a state variable is governed linearly too. Nothing has been
    approximated and nothing has been linearised about anything.
    """
    )
    return


