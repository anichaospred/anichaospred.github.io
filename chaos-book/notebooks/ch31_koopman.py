@app.cell(hide_code=True)
def s4_md(mo):
    mo.md(
        r"""
    ## 4 · What actually breaks: the iteration leaves the manifold

    Here is the fact that explains section 3. At a lead of 0.05 time units the
    304-observable model's error is $2\times10^{-4}$ of the climatological spread. Its
    one-step accuracy is superb. Six steps later it has lost more than half of it.

    That is far faster than error growth at $\lambda_1$ can explain, so something other
    than chaos is at work — and it is geometric.

    The dictionary vectors that are *the dictionary of some state* form a
    three-dimensional surface inside the 304-dimensional dictionary space: the image of
    the lift. Every fitted relation holds on that surface, because every training pair
    lay on it. **$\mathbf{K}$ does not preserve it.** One step from the surface lands
    slightly off it; the next step is then applying an operator to a vector it was never
    fitted for, and the error compounds geometrically rather than dynamically.

    This is measurable directly. Take the rolled-out vector, read the state out of it,
    rebuild the dictionary from that state, and compare:

    $$
    \text{drift} =
      \frac{\left\|g - \mathrm{dict}(Pg)\right\|}{\left\|\mathrm{dict}(Pg)\right\|},
    $$

    zero for anything on the surface. And it suggests the obvious repair: **re-lift at
    every step** — advance, read the state out, rebuild the dictionary from it, advance
    again — which forces the iteration back onto the surface each time.
    """
    )
    return


