@app.cell(hide_code=True)
def s2_md(mo):
    mo.md(
        r"""
    ## 2 · Extended DMD on a chaotic attractor

    With no closing dictionary available, fit the best operator on whatever dictionary
    is at hand. Given snapshot pairs, **extended dynamic mode decomposition** solves

    $$
    \mathbf{K} = \arg\min_{\mathbf{K}}\;\left\|G_y - G_x\mathbf{K}\right\|_F ,
    $$

    one row per pair, so that $g(x_{n+1})^{\!\top} \approx g(x_n)^{\!\top}\mathbf{K}$.
    ($\mathbf{K}$ is the Kalman gain everywhere in Part V and the compressed Koopman
    operator everywhere in this chapter. Both are standard; they do not meet.)
    Plain **DMD** is the same thing with the dictionary reduced to a constant and the
    state itself, which is worth saying plainly: DMD is not a different method, it is
    EDMD with the smallest dictionary anyone uses.

    The system is Lorenz 63, sampled every $\tau = 0.05$ time units, whitened, and the
    dictionary is a constant, the three state variables, and $k$ Gaussian bumps centred
    on states the trajectory actually visited. (Centres drawn from the trajectory, not
    from a grid: chapter 30 measured how little of the bounding box the attractor
    occupies, and a grid would spend most of its basis functions on empty space.)
    """
    )
    return


