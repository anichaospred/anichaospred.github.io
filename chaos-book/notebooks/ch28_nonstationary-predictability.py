@app.cell(hide_code=True)
def s5_md(DENSE_EVERY, DENSE_FORCING, DENSE_N, N_LAUNCH, mo):
    mo.md(
        rf"""
    ## 5 · How long a record does a trend need?

    Sections 1 to 4 had {N_LAUNCH:,.0f} frozen-system forecasts and a predictability
    change of fifty per cent. An operational centre has neither. It has one forecast a day from a
    system that changed continuously, and — if the atmosphere's predictability is moving
    at all — a change of a few per cent per decade to find.

    Two facts set the answer, and the first is usually ignored.

    **A forecast a day is not a forecast's worth of information a day.** Two forecasts
    launched a day apart verify against an atmosphere that has barely changed, so their
    errors are strongly correlated. Below, {DENSE_N:,.0f} forecasts launched
    ${DENSE_EVERY:g}$ time units apart — one per day — at $F = {DENSE_FORCING:.1f}$, with
    the effective sample size

    $$ n_{{\rm eff}} = \frac{{n}}{{1 + 2\sum_{{k\ge1}}\rho_k}} $$

    truncated at the first non-positive $\rho_k$.

    **And the record's length is worth far more than its density.** For $n$ epochs with
    $m$ independent cases each, $S_{{xx}} = m\,n(n^2-1)/12$, so

    $$
    \operatorname{{se}}(b) = \frac{{\sigma}}{{\sqrt{{m\,n(n^2-1)/12}}}}
    \;\propto\; m^{{-1/2}}\,n^{{-3/2}} .
    $$

    Doubling the cases per year buys a factor $\sqrt2$. **Doubling the length of the
    record buys $2\sqrt2$.**
    """
    )
    return


