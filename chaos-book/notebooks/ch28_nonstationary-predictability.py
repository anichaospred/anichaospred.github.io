@app.cell(hide_code=True)
def s1_md(
    DELTA0_OLD, F_END, F_START, LEAD, N_EPOCH, N_LAUNCH, PER_EPOCH,
    RAMP_DF_PER_FORECAST, RECORD_YEARS, TOTAL, mo,
):
    mo.md(
        rf"""
    ## 1 · A frozen system on a changing atmosphere

    The confound in its cleanest form: change the atmosphere and **nothing else**.

    The truth run ramps from $F = {F_START:g}$ to $F = {F_END:g}$ over
    ${TOTAL:,.0f}$ time units — about {RECORD_YEARS:.0f} years at the conventional
    five days per time unit. {N_LAUNCH:,} forecasts are launched along it,
    {PER_EPOCH} in each of {N_EPOCH:.0f} equal epochs, each run to lead
    ${LEAD:g}$ time units against the truth. Every forecast uses the same perfect
    model and the same analysis error, ${DELTA0_OLD:g}$ per component. **The
    forecasting system does not change at any point in the record.**

    Two conventions for "how long is this forecast useful", both in operational use:

    * **normalised** — the error reaches half of *this* epoch's climatological
      saturation, the analogue of a fixed anomaly-correlation threshold;
    * **fixed** — the error reaches half of the *first* epoch's saturation, the
      analogue of a fixed absolute error tolerance in metres or kelvin.

    They are the same measurement of the same forecasts and they differ only in the
    denominator. Move the slider and watch the trend change.

    Reading the ramp as a sequence of climates is a claim, not a definition: over one
    {LEAD:g}-time-unit forecast the forcing moves by only
    ${RAMP_DF_PER_FORECAST:.3f}$, so it should be legitimate. Section 2 checks it
    against stationary runs rather than assuming it.
    """
    )
    return


